import { describe, expect, it } from 'vitest';
import { formatLocation, labelOperands, matchesBank, parseLocation, parseSymbols } from './symbols';

const SYM = `; File generated by rgblink
00:0150 Main
00:0150 Main.start
00:0153 Main.loop
02:4000 Bank2Routine
03:4000 Bank3Routine
00:c000 wCounter
00:ff80 hFlag   ; HRAM
not a symbol line
`;

describe('symbols', () => {
  const symbols = parseSymbols(SYM);

  it('reads RGBDS .sym files, telling banks apart only in switchable ROM', () => {
    expect(symbols.count).toBe(7);
    expect(symbols.labelAt(0x150, 5)).toBe('Main'); // a routine's name beats its local label
    expect(symbols.labelAt(0x153, 0)).toBe('Main.loop');
    expect(symbols.labelAt(0x4000, 2)).toBe('Bank2Routine');
    expect(symbols.labelAt(0x4000, 3)).toBe('Bank3Routine');
    expect(symbols.labelAt(0x4000, 4)).toBeNull();
    expect(symbols.labelAt(0xc000, 7)).toBe('wCounter');
    expect(symbols.find('bank3routine')).toEqual({ addr: 0x4000, bank: 3 });
    expect(symbols.find('wCounter')).toEqual({ addr: 0xc000, bank: null });
    expect(parseSymbols('nothing here').count).toBe(0);
  });

  it('parses typed locations: hex, bank:address or a label', () => {
    expect(parseLocation('$C000', null)).toEqual({ addr: 0xc000, bank: null });
    expect(parseLocation('03:4567', null)).toEqual({ addr: 0x4567, bank: 3 });
    // A bank only means something in switchable ROM.
    expect(parseLocation('01:C000', null)).toEqual({ addr: 0xc000, bank: null });
    expect(parseLocation('Main.loop', symbols)).toEqual({ addr: 0x153, bank: null });
    expect(parseLocation('Main.loop', null)).toBeNull();
    expect(parseLocation('100:4000', symbols)).toBeNull();
    expect(formatLocation({ addr: 0x4567, bank: 3 })).toBe('03:4567');
    expect(formatLocation({ addr: 0xc000, bank: null })).toBe('$C000');
    expect(matchesBank({ addr: 0x4000, bank: 3 }, 3)).toBe(true);
    expect(matchesBank({ addr: 0x4000, bank: 3 }, 2)).toBe(false);
    expect(matchesBank({ addr: 0x4000, bank: null }, 2)).toBe(true);
  });

  it('names the addresses in disassembled operands', () => {
    expect(labelOperands('CALL $4000', symbols, 3)).toBe('CALL Bank3Routine');
    expect(labelOperands('JR $0153', symbols, 1)).toBe('JR Main.loop');
    expect(labelOperands('LD ($FF00+$80),A', symbols, 1)).toBe('LD (hFlag),A');
    expect(labelOperands('LD ($FF00+$40),A', symbols, 1)).toBe('LD ($FF00+$40),A');
    expect(labelOperands('LD A,($C000)', symbols, 1)).toBe('LD A,(wCounter)');
    expect(labelOperands('LD A,($C000)', null, 1)).toBe('LD A,($C000)');
  });
});
